RESEARCH_TOPIC = "宁波商业地产租赁市场"

def fetch_ningbo_commercial_data():
    """抓取宁波商业地产数据"""

    headers = {
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36',
        'Accept': 'text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8',
        'Accept-Language': 'zh-CN,zh;q=0.8,en;q=0.5',
    }

    results = {
        'topic': RESEARCH_TOPIC,
        'data_time': '2026-02-01',
        'sources': [],
        'market_data': {}
    }

    # 调研宁波主要房产平台
    sources = [
        {
            'name': '房天下-宁波商铺',
            'url': 'https://nb.shop.fang.com/zu/',
            'type': '商铺'
        },
        {
            'name': '房天下-宁波写字楼',
            'url': 'https://nb.shop.fang.com/zu/o3/',
            'type': '写字楼'
        },
        {
            'name': '贝壳找房-宁波商业地产',
            'url': 'https://nb.fang.com/chuzu/',
            'type': '综合'
        }
    ]

    for source in sources:
        try:
            print(f"正在调研: {source['name']}...")
            response = requests.get(source['url'], headers=headers, timeout=15)

            if response.status_code == 200:
                soup = BeautifulSoup(response.text, 'html.parser')

                # 提取租金信息
                rentals = []
                price_elements = soup.find_all(text=re.compile(r'\d+[.-]\d+元'))
                for elem in price_elements[:10]:
                    rentals.append(elem.strip())

                results['market_data'][source['type']] = {
                    'source': source['name'],
                    'url': source['url'],
                    'status': 'success',
                    'rentals_found': rentals[:5]
                }
                results['sources'].append(source['name'])
            else:
                results['market_data'][source['type']] = {
                    'source': source['name'],
                    'status': 'failed',
                    'error': f'HTTP {response.status_code}'
                }

            time.sleep(1)

        except Exception as e:
            results['market_data'][source['type']] = {
                'source': source['name'],
                'status': 'error',
                'error': str(e)
            }

    return results

