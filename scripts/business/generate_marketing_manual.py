def perform_deep_research(skill, keywords):
    print(f"🔍 开始深度调研: {' '.join(keywords)} ...")
    research_results = []
    
    # Simulate a sophisticated research loop
    for query in keywords:
        print(f"  - 正在搜索: {query}")
        # Note: The current WebSearchSkill uses a mock implementation. 
        # In a real scenario, this would hit the web.
        # We will proceed with the mock/existing capabilities as verification.
        result = skill.search(query, max_results=5)
        research_results.append(f"### Search Query: {query}\n")
        
        if result.get('results'):
            for item in result['results']:
                research_results.append(f"- Title: {item.get('title')}")
                research_results.append(f"  Snippet: {item.get('snippet')}")
                research_results.append(f"  Source: {item.get('source')}\n")
        else:
            research_results.append("  No results found.\n")
            
    return "\n".join(research_results)

